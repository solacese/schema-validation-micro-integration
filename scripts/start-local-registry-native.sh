#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

"${ROOT_DIR}/scripts/prepare-local-registry-runtime.sh"

USER_API_SECRET="${API_SECRET-}"
USER_DEVELOPER_PASSWORD="${DEVELOPER_PASSWORD-}"
USER_READONLY_PASSWORD="${READONLY_PASSWORD-}"
USER_PROTOCOL="${PROTOCOL-}"
USER_IDP_KEY="${IDP_KEY-}"
USER_IDP_HOST_PORT="${IDP_HOST_PORT-}"
USER_IDP_ADDRESS="${IDP_ADDRESS-}"
USER_REGISTRY_UI_ADDRESS="${REGISTRY_UI_ADDRESS-}"
USER_REGISTRY_API_HOST_HTTP_PORT="${REGISTRY_API_HOST_HTTP_PORT-}"
USER_REGISTRY_API_ADDRESS="${REGISTRY_API_ADDRESS-}"
USER_REGISTRY_POSTGRES_HOST_PORT="${REGISTRY_POSTGRES_HOST_PORT-}"

set -a
source "${ROOT_DIR}/.runtime/schema-registry/.env"
set +a

export API_SECRET="${USER_API_SECRET:-${API_SECRET:-apiSecret}}"
export DEVELOPER_PASSWORD="${USER_DEVELOPER_PASSWORD:-${DEVELOPER_PASSWORD:-devPassword}}"
export READONLY_PASSWORD="${USER_READONLY_PASSWORD:-${READONLY_PASSWORD:-roPassword}}"
export PROTOCOL="${USER_PROTOCOL:-${PROTOCOL:-http}}"
export IDP_KEY="${USER_IDP_KEY:-${IDP_KEY}}"
export IDP_HOST_PORT="${USER_IDP_HOST_PORT:-13000}"
export IDP_ADDRESS="${USER_IDP_ADDRESS:-localhost:${IDP_HOST_PORT}}"
export REGISTRY_UI_ADDRESS="${USER_REGISTRY_UI_ADDRESS:-localhost:18888}"
export REGISTRY_API_HOST_HTTP_PORT="${USER_REGISTRY_API_HOST_HTTP_PORT:-18081}"
export REGISTRY_API_ADDRESS="${USER_REGISTRY_API_ADDRESS:-localhost:${REGISTRY_API_HOST_HTTP_PORT}}"
export REGISTRY_POSTGRES_HOST_PORT="${USER_REGISTRY_POSTGRES_HOST_PORT:-15432}"

docker compose -f "${ROOT_DIR}/docker-compose.registry-native.yml" up -d
